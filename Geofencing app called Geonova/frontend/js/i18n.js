class I18nManager {
    constructor() {
        this.currentLang = localStorage.getItem('geonova_lang') || 'en';
    }

    init() {
        const selector = document.getElementById('language-select');
        if (selector) {
            selector.value = this.currentLang;
            selector.addEventListener('change', (e) => {
                this.setLanguage(e.target.value);
            });
        }
        this.applyTranslations();
    }

    setLanguage(lang) {
        if (!translations[lang]) return;
        this.currentLang = lang;
        localStorage.setItem('geonova_lang', lang);
        this.applyTranslations();
        
        const langNames = {
            en: "English",
            hi: "हिन्दी (Hindi)",
            es: "Español (Spanish)",
            fr: "Français (French)",
            zh: "中文 (Chinese)",
            de: "Deutsch (German)"
        };
        if (window.showToast) {
            window.showToast(`Language set to ${langNames[lang]}`, 'info');
        }
    }

    getText(key) {
        const dict = translations[this.currentLang] || translations['en'];
        return dict[key] || translations['en'][key] || key;
    }

    applyTranslations() {
        const dict = translations[this.currentLang] || translations['en'];
        const fallback = translations['en'];

        // Elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(elem => {
            const key = elem.getAttribute('data-i18n');
            elem.innerHTML = dict[key] || fallback[key] || key;
        });

        // Elements with data-i18n-placeholder attribute
        document.querySelectorAll('[data-i18n-placeholder]').forEach(elem => {
            const key = elem.getAttribute('data-i18n-placeholder');
            elem.placeholder = dict[key] || fallback[key] || key;
        });

        // Update document title and html lang
        document.documentElement.lang = this.currentLang;
    }
}

const i18n = new I18nManager();
window.i18n = i18n;
